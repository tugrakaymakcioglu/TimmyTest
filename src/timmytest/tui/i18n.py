class Translator:
    """Tiny mutable translator so screens can swap language without a restart."""

    def __init__(self, language: str = "tr") -> None:
        self.language = language if language in TRANSLATIONS else "tr"

    def set_language(self, language: str) -> None:
        if language in TRANSLATIONS:
            self.language = language

    def __call__(self, key: str, **kwargs: object) -> str:
        table = TRANSLATIONS.get(self.language, TRANSLATIONS["tr"])
        text = table.get(key) or TRANSLATIONS["en"].get(key) or key
        if kwargs:
            try:
                return text.format(**kwargs)
            except (KeyError, IndexError, ValueError):
                return text
        return text
